// Pre-build a Map for O(1) lookup
const ZIP_INDEX: Map<string, DkZipPoint> = new Map();
for (const p of DK_ZIP_CENTROIDS) ZIP_INDEX.set(p.zip, p);

// Fallback prefix → centroid (calculated as avg of all zips with that prefix)
const PREFIX_INDEX: Map<string, { lat: number; lng: number }> = (() => {
  const buckets = new Map<string, { sumLat: number; sumLng: number; count: number }>();
  for (const p of DK_ZIP_CENTROIDS) {
    const prefix = p.zip.slice(0, 2);
    const b = buckets.get(prefix) || { sumLat: 0, sumLng: 0, count: 0 };
    b.sumLat += p.lat;
    b.sumLng += p.lng;
    b.count += 1;
    buckets.set(prefix, b);
  }
  const result = new Map<string, { lat: number; lng: number }>();
  for (const [prefix, b] of buckets) {
    result.set(prefix, { lat: b.sumLat / b.count, lng: b.sumLng / b.count });
  }
  return result;
})();

/**
 * Look up a Danish zip code's approximate centroid.
 * - Returns the exact match if known.
 * - Otherwise interpolates from the same 2-digit prefix (region average).
 * - Returns null only if the prefix is also unknown.
 */
export const lookupDkZip = (zip?: string | null): { lat: number; lng: number } | null => {
  if (!zip) return null;
  const z = String(zip).trim();
  if (!/^\d{4}$/.test(z)) return null;
  const direct = ZIP_INDEX.get(z);
  if (direct) return { lat: direct.lat, lng: direct.lng };
  const prefix = z.slice(0, 2);
  const fallback = PREFIX_INDEX.get(prefix);
  return fallback || null;
};

/**
 * Haversine distance between two coordinates in kilometres.
 */
export const haversineKm = (
  a: { lat: number; lng: number },
  b: { lat: number; lng: number },
): number => {
  const R = 6371; // Earth radius in km
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.sin(dLng / 2) ** 2 * Math.cos(lat1) * Math.cos(lat2);
  return 2 * R * Math.asin(Math.sqrt(h));
};

/**
 * Distance in km between two Danish zip codes. Returns null if either can't be resolved.
 */
export const distanceBetweenZipsKm = (
  a?: string | null,
  b?: string | null,
): number | null => {
  const pa = lookupDkZip(a);
  const pb = lookupDkZip(b);
  if (!pa || !pb) return null;
  return haversineKm(pa, pb);
};

